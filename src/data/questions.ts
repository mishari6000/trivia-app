/** Compact builder for a category's Arabic questions; ids are `<prefix>-001` … */
function category(
  name: CategoryName,
  prefix: string,
  items: [question: string, correctAnswer: string, incorrectAnswers: [string, string, string]][],
): Question[] {
  return items.map(([question, correctAnswer, incorrectAnswers], i) => ({
    id: `${prefix}-${String(i + 1).padStart(3, '0')}`,
    category: name,
    language: 'ar',
    question,
    correctAnswer,
    incorrectAnswers,
  }));
}
