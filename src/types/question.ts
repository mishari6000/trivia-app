export type QuestionLanguage = 'ar' | 'en';

/** Category names are exactly Open Trivia DB's, so internet questions map straight in. */
export type CategoryName =
  | 'General Knowledge'
  | 'Entertainment: Books'
  | 'Entertainment: Film'
  | 'Entertainment: Music'
  | 'Entertainment: Musicals & Theatres'
  | 'Entertainment: Television'
  | 'Entertainment: Video Games'
  | 'Entertainment: Board Games'
  | 'Science & Nature'
  | 'Science: Computers'
  | 'Science: Mathematics'
  | 'Mythology'
  | 'Sports'
  | 'Geography'
  | 'History'
  | 'Politics'
  | 'Art'
  | 'Celebrities'
  | 'Animals'
  | 'Vehicles'
  | 'Entertainment: Comics'
  | 'Science: Gadgets'
  | 'Entertainment: Japanese Anime & Manga'
  | 'Entertainment: Cartoon & Animations'
  /** «صمم فئتك»: the player's own topic, with questions generated by AI on demand. */
  | 'Custom';

/** The 24 categories the shipped bank covers (everything but the player's own). */
export type BankCategoryName = Exclude<CategoryName, 'Custom'>;

/** The level a player picks for each category. */
export type Difficulty = 'easy' | 'medium' | 'hard';

/** Raw question shape, shared by the hand-written bank and the generated one. */
export type Question = {
  id: string;
  category: CategoryName;
  language: QuestionLanguage;
  question: string;
  correctAnswer: string;
  incorrectAnswers: [string, string, string];
};

/** One generated question in src/data/bank.json (always Arabic). */
export type BankQuestion = Omit<Question, 'language'> & { difficulty: Difficulty };

export type Bank = {
  meta: { spentUsd: number; writer: string[]; checker: string[]; updatedAt: string | null };
  questions: BankQuestion[];
};

export type AnswerOption = {
  /** Stable ID, independent of display position. */
  id: string;
  text: string;
};

/** A validated question ready for play. Correctness is decided by option ID. */
export type PlayableQuestion = {
  id: string;
  category: Question['category'];
  language: QuestionLanguage;
  question: string;
  options: AnswerOption[];
  correctOptionId: string;
};
